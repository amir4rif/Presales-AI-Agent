create or replace view public.my_proposals
with (security_invoker = true)
as
select *
from public.proposals
where status not in ('Superseded', 'Reject & Close')
  and owner_id = (select auth.uid());

create or replace view public.admin_approvals
with (security_invoker = true)
as
select *
from public.proposals
where status = 'Pending Review';

create or replace view public.proposal_version_history
with (security_invoker = true)
as
select *
from public.proposals
order by case_id, version;

-- New Supabase projects no longer expose new public tables automatically.
-- These grants opt authenticated users into the Data API; RLS still controls rows.
