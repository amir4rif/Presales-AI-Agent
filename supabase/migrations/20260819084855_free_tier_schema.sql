create schema if not exists private;
revoke all on schema private from public;

create sequence if not exists public.proposal_number_seq as bigint start with 151;
create sequence if not exists public.case_number_seq as bigint start with 94;

create or replace function private.next_proposal_id()
returns text
language sql
volatile
security invoker
set search_path = ''
as $$
  select 'PROP-' || extract(year from current_date)::integer::text || '-' ||
         lpad(nextval('public.proposal_number_seq'::regclass)::text, 6, '0')
$$;

create or replace function private.next_case_id()
returns text
language sql
volatile
security invoker
set search_path = ''
as $$
  select 'CASE-' || extract(year from current_date)::integer::text || '-' ||
         lpad(nextval('public.case_number_seq'::regclass)::text, 6, '0')
$$;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  first_name text not null default '',
  last_name text not null default '',
  full_name text not null,
  email text not null unique,
  role text not null default 'Sales Representative',
  level smallint not null default 1 check (level between 1 and 3),
  status text not null default 'active' check (status in ('active', 'inactive')),
  last_active timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.proposals (
  id text primary key default private.next_proposal_id(),
  case_id text not null default private.next_case_id(),
  opportunity_id text not null default '',
  version integer not null default 1 check (version > 0),
  company text not null,
  deal text not null,
  value numeric(14, 2) not null default 0 check (value >= 0),
  submitted_by_id uuid not null default auth.uid() references public.profiles(id),
  submitted_by text not null,
  owner_id uuid not null default auth.uid() references public.profiles(id),
  owner text not null,
  generated_on date not null default current_date,
  submitted_at timestamptz,
  status text not null default 'Draft' check (
    status in ('Draft', 'Pending Review', 'Approved', 'Reject & Revise', 'Reject & Close', 'Superseded')
  ),
  reviewer_id uuid references public.profiles(id),
  reviewer text not null default '',
  reviewed_at timestamptz,
  rejection_reason text not null default '',
  review_note text not null default '',
  sections jsonb not null default '{}'::jsonb check (jsonb_typeof(sections) = 'object'),
  outcome text check (outcome is null or outcome in ('Pending', 'Won', 'Lost')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (case_id, version)
);

