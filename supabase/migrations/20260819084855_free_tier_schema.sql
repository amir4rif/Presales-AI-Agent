create or replace function private.current_access_level()
returns smallint
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (select p.level from public.profiles as p where p.id = (select auth.uid())),
    0
  )::smallint
$$;

create or replace function private.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  given_name text := coalesce(new.raw_user_meta_data ->> 'first_name', '');
  family_name text := coalesce(new.raw_user_meta_data ->> 'last_name', '');
  display_name text;
begin
  display_name := nullif(trim(concat_ws(' ', given_name, family_name)), '');
  display_name := coalesce(display_name, split_part(coalesce(new.email, ''), '@', 1), 'User');

  insert into public.profiles (
    id, first_name, last_name, full_name, email, role, level
  ) values (
    new.id,
    given_name,
    family_name,
    display_name,
    coalesce(new.email, new.id::text || '@pending.local'),
    'Sales Representative',
    1
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

create or replace function private.protect_profile_access()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if current_user not in ('postgres', 'service_role', 'supabase_admin') and
     private.current_access_level() < 3 and
     (new.id, new.email, new.role, new.level) is distinct from
     (old.id, old.email, old.role, old.level) then
    raise exception 'Only Level 3 administrators can change profile access.'
      using errcode = '42501';
  end if;
  return new;
end;
$$;

create or replace function private.enforce_proposal_workflow()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  access_level smallint := private.current_access_level();
begin
  if access_level >= 2 or current_user in ('postgres', 'service_role', 'supabase_admin') then
    return new;
  end if;

  if tg_op = 'INSERT' then
    if new.owner_id is distinct from (select auth.uid()) or
       new.submitted_by_id is distinct from (select auth.uid()) or
       new.status not in ('Draft', 'Pending Review') or
       new.reviewer_id is not null or new.reviewer <> '' or
       new.reviewed_at is not null or new.rejection_reason <> '' or
       new.review_note <> '' or new.outcome is not null then
      raise exception 'Level 1 users can only create their own draft or pending proposals.'
        using errcode = '42501';
    end if;
    return new;
  end if;

  if new.owner_id is distinct from old.owner_id or
     new.submitted_by_id is distinct from old.submitted_by_id or
     new.reviewer_id is distinct from old.reviewer_id or
     new.reviewer is distinct from old.reviewer or
     new.reviewed_at is distinct from old.reviewed_at or
     new.rejection_reason is distinct from old.rejection_reason or
     new.review_note is distinct from old.review_note or
     new.outcome is distinct from old.outcome then
    raise exception 'Level 1 users cannot change reviewer-controlled proposal fields.'
      using errcode = '42501';
  end if;

  if not (
    (old.status = 'Draft' and new.status in ('Draft', 'Pending Review')) or
    (old.status = 'Pending Review' and new.status = 'Pending Review') or
    (old.status = 'Reject & Revise' and new.status in ('Reject & Revise', 'Superseded')) or
    (old.status = new.status)
  ) then
    raise exception 'This proposal status transition requires a reviewer.'
      using errcode = '42501';
  end if;

  return new;
end;
$$;

